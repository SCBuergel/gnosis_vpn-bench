# Cells up to this many characters never wrap, so a narrow screen scrolls the
# table sideways instead of squeezing columns to a few characters wide.
WRAP_AFTER_CHARS = 40


def _cell(text: str) -> str:
    css = ' class="wide"' if len(text) > WRAP_AFTER_CHARS else ""
    return f"<td{css}>{escape(text)}</td>"


def table(headers: list[str], rows: list[list[Any]]) -> str:
    head = "".join(f"<th>{escape(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(_cell(fmt(v)) for v in row) + "</tr>" for row in rows)
    return f'<div class="scroll"><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>'


def _block(block: Block) -> str:
    if isinstance(block, Heading):
        anchor = f' id="{escape(block.anchor, quote=True)}"' if block.anchor else ""
        return f"<h{block.level}{anchor}>{escape(block.text)}</h{block.level}>"
    if isinstance(block, Paragraph):
        css = "warn" if block.warn else "muted" if block.muted else ""
        return f'<p class="{css}">{escape(block.text)}</p>'
    if isinstance(block, Table):
        return table(block.headers, block.rows)
    if isinstance(block, Chart):
        return block.draw(HTML_THEME)
    raise TypeError(block)


def body_html(collection: Collection) -> str:
    """Header plus one <section> per top-level section."""
    sections: list[list[str]] = []
    for block in build(collection):
        if isinstance(block, Heading) and block.level == 2:
            sections.append([])
        sections[-1].append(_block(block))
    badge = ""
    if any(not r.result["run"]["reproducible"] for r in collection.recordings):
        badge = ' <span class="warn">· includes historical, non-reproducible data</span>'
    header = f'<h1>{escape(collection.title)}</h1><p class="muted">{escape(subtitle(collection))}{badge}</p>'
    return header + "".join(f"<section>{''.join(parts)}</section>" for parts in sections)


def render_collection(collection: Collection) -> str:
    for recording in collection.recordings:
        validate(recording.result)
    return (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        f"<title>{escape(collection.title)}</title><style>{CSS}</style></head>"
        f"<body><main>{body_html(collection)}"
        "<footer>Generated by gnosis_vpn-bench from result.json (schema 1.0). "
        "No JavaScript or external resources.</footer></main></body></html>\n"
    )


def default_title(result: dict[str, Any]) -> str:
    return f"{result['provenance']['target']['label']} · {result['provenance']['profile']['name']}"


def render(result: dict[str, Any], name: str | None = None) -> str:
    """A report for a single recording."""
    validate(result)
    recording = Recording(name=name or result["run"]["id"], result=result)
    return render_collection(Collection(title=f"Gnosis VPN: {default_title(result)}", recordings=[recording]))
